#!/usr/bin/env python3
"""Generate delivery subsets from committed fonts; never runs during site builds.

Maintenance dependencies: fonttools[woff]==4.61.1 and brotli==1.2.0.
Original fonts, outlines, hinting, variable axes and OFL notices are retained.
"""

import hashlib
import io
import json
from pathlib import Path

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "src/_includes/fonts"
NOTO_DIR = ROOT / "src/assets/fonts/noto"
SOURCES = [
    ("source-sans-3-variable", "Source Sans 3", "normal", "Prongs Sans Web",
     "5f16566f7a40d39b339ad26be151fa5a1ab1f0c2574c7a2e619765584a1acbd8"),
    ("source-sans-3-variable-italic", "Source Sans 3", "italic", "Prongs Sans Web",
     "b4959abc0569392f87c6c6ac612f90e3fe0104d283724189b7d8b6f61af347d3"),
    ("source-serif-4-variable", "Source Serif 4", "normal", "Prongs Serif Web",
     "940a76eda1388de39d38c8e7a79bf6ea058a387faee0a9f33c8d25c6ba05e1be"),
]
# Latin-1 letters, combining accents, and common prose punctuation.
# Every other original codepoint remains available through the full-font face.
LATIN = set(range(0x0000, 0x0100)) | set(range(0x0300, 0x0370))
LATIN |= set(range(0x2000, 0x2070))
LATIN |= set(range(0xFB00, 0xFB05))  # Typeset emits literal fi/fl ligature characters.
LATIN |= {0x0131, 0x0152, 0x0153, 0x02BB, 0x02BC, 0x02C6, 0x02DA, 0x02DC,
          0x20AC, 0x2122, 0x2191, 0x2193, 0x2212, 0x2215, 0xFEFF, 0xFFFD}
NAME_POINTS = set(map(ord, "时光"))


def ranges(points):
    spans = []
    for point in sorted(points):
        if spans and spans[-1][1] + 1 == point:
            spans[-1][1] = point
        else:
            spans.append([point, point])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


def points(value):
    output = set()
    for part in value.split(","):
        if not part:
            continue
        a, *b = part.strip()[2:].split("-")
        output.update(range(int(a, 16), int(b[0], 16) + 1) if b else [int(a, 16)])
    return output


def subset_bytes(source, codepoints, internal_family=None):
    font = TTFont(io.BytesIO(source), recalcTimestamp=False)
    options = subset.Options()
    options.flavor = "woff2"
    # Retain FontTools' standard shaping/kerning/ligature features and the
    # tabular figures used by this site's date/table CSS, plus small caps
    # emitted by Typeset and slashed zero. Other optional display alternates
    # are omitted from these delivery subsets.
    options.layout_features.extend(["tnum", "smcp", "c2sc", "zero"])
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    # Adobe reserves "Source" for original font names. Only the generated
    # subset's internal family identifiers change; CSS keeps the selected alias.
    # Copyright, attribution, trademark, license and original files are intact.
    if internal_family:
        for record in font["name"].names:
            if record.nameID in {1, 3, 4, 6, 16, 18, 20, 21, 25} or record.nameID >= 256:
                value = record.toUnicode()
                for original in ("Source Sans 3", "Source Serif 4"):
                    value = value.replace(original, internal_family)
                    value = value.replace(original.replace(" ", ""), internal_family.replace(" ", ""))
                record.string = value.encode(record.getEncoding())
    font.flavor = "woff2"
    output = io.BytesIO()
    font.save(output)
    return output.getvalue()


def face(family, filename, weight, unicode_range, style="normal"):
    return (f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n"
            f"  font-weight: {weight};\n  font-display: swap;\n"
            f"  src: url('{filename}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n}}")


def source_fonts():
    css = ["/* Generated by scripts/optimize-site-fonts.py. */",
           "/* Latin subsets preserve variable axes; full originals cover other scripts. */"]
    manifest = {"fontToolsVersion": fontTools.__version__, "fonts": []}
    keep = set()
    for stem, family, style, internal_family, expected in SOURCES:
        source_path = SOURCE_DIR / f"{stem}.woff2"
        source = source_path.read_bytes()
        if hashlib.sha256(source).hexdigest() != expected:
            raise ValueError(f"Original font changed: {source_path.name}; review and update its checksum")
        original = TTFont(io.BytesIO(source))
        original_points = set(original.getBestCmap())
        selected = original_points & LATIN
        remainder = original_points - selected
        data = subset_bytes(source, selected, internal_family)
        digest = hashlib.sha256(data).hexdigest()
        filename = f"{stem}-latin.{digest[:12]}.woff2"
        keep.add(filename)
        (SOURCE_DIR / filename).write_bytes(data)
        css.append(face(family, f"/_includes/fonts/{filename}", "200 900", ranges(selected), style))
        css.append(face(family, f"/_includes/fonts/{stem}.woff2", "200 900", ranges(remainder), style))
        manifest["fonts"].append({
            "family": family, "style": style, "file": filename,
            "bytes": len(data), "sha256": digest, "unicodeRange": ranges(selected),
            "originalFile": source_path.name, "originalSha256": expected,
            "fallbackUnicodeRange": ranges(remainder),
            "axes": [{"tag": a.axisTag, "min": a.minValue, "default": a.defaultValue,
                      "max": a.maxValue} for a in original["fvar"].axes],
        })
        print(f"{family} {style}: {len(source):,} → {len(data):,} Latin bytes")
    for path in SOURCE_DIR.glob("source-*-latin.*.woff2"):
        if path.name not in keep:
            path.unlink()
    (ROOT / "src/_includes/css/font.css").write_text("\n\n".join(css) + "\n")
    (SOURCE_DIR / "delivery-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


def noto_name():
    manifest_path = NOTO_DIR / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    family = manifest["families"]["Noto Sans SC"]
    common = family["common"]
    common_points = points(common.get("originalUnicodeRange", common["unicodeRange"]))
    if not NAME_POINTS <= common_points:
        raise ValueError("Refresh Noto common fonts first; name glyphs are missing")
    source = (NOTO_DIR / common["file"]).read_bytes()
    data = subset_bytes(source, NAME_POINTS)
    digest = hashlib.sha256(data).hexdigest()
    filename = f"noto-sans-sc-name.{digest[:12]}.woff2"
    (NOTO_DIR / filename).write_bytes(data)
    family["name"] = {
        "file": filename, "bytes": len(data), "sha256": digest,
        "unicodeRange": ranges(NAME_POINTS), "characterCount": len(NAME_POINTS),
        "sourceFile": common["file"], "sourceSha256": hashlib.sha256(source).hexdigest(),
        "weightAxis": common["weightAxis"], "fontToolsVersion": fontTools.__version__,
    }
    common["originalUnicodeRange"] = ranges(common_points)
    common["unicodeRange"] = ranges(common_points - NAME_POINTS)
    common["originalCharacterCount"] = len(common_points)
    common["characterCount"] = len(common_points - NAME_POINTS)
    css = ["/* Generated by scripts/update-noto-fonts.py and scripts/optimize-site-fonts.py. */",
           "/* Name, common, and full fallback ranges are disjoint. */"]
    for family_name, details in manifest["families"].items():
        for key in ("name", "common"):
            if key in details:
                item = details[key]
                axis = item["weightAxis"]
                css.append(face(family_name, f"./{item['file']}",
                                f"{float(axis['min']):g} {float(axis['max']):g}", item["unicodeRange"]))
        axis = details["weightAxis"]
        for item in details["files"]:
            if item["unicodeRange"]:
                css.append(face(family_name, f"./{item['file']}",
                                f"{float(axis['min']):g} {float(axis['max']):g}", item["unicodeRange"]))
    (NOTO_DIR / "fonts.css").write_text("\n\n".join(css) + "\n")
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    for old in NOTO_DIR.glob("noto-sans-sc-name.*.woff2"):
        if old.name != filename:
            old.unlink()
    print(f"Noto Sans SC name: {len(data):,} bytes for 时光")


if __name__ == "__main__":
    source_fonts()
    noto_name()
